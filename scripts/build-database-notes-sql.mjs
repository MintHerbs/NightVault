#!/usr/bin/env node
// Emits the SQL that puts the augmented Database Systems notes into the
// `notes` table.
//
//   node scripts/build-database-notes-sql.mjs > database-notes-upsert.sql
//
// The notes already exist upstream, so every statement is an UPDATE matched on
// (module_id, path). Nothing is created and nothing is deleted; a path that no
// longer matches is reported by the run rather than silently inserting a
// duplicate note.
//
// Authorship. Three triggers on public.notes call auth.uid():
// notes_set_metadata_trg, notes_track_author_trg (whose note_authors.user_id is
// NOT NULL, so it aborts outright without a JWT) and
// notes_freeze_created_at_trg. Running this from the SQL editor has no JWT, so
// the transaction sets request.jwt.claims to NOORIE's id. These are her notes
// and the augmentation is an addition to her work, not a takeover of it, so the
// author recorded must stay hers.

import { readFile, readdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'

const ROOT = new URL('..', import.meta.url)
const AUG = new URL('preview-notes/', ROOT)
const ORIG = new URL('preview-notes-original/', ROOT)

/** Noorie, owner and author of all 21 database notes. */
const AUTHOR = 'f4fbb1be-fcca-4e72-84f5-e3c22d658e26'
const AUTHOR_NAME = 'Noorie'
const MODULE = 'database'

// The local dump flattened '/' and ' ' to '_', which is lossy, so the real
// paths are listed here rather than reconstructed by guessing.
const PATHS = {
  'Semester_1_lecture-3-Data_Definition_Language.md': 'Semester 1/lecture-3-Data Definition Language',
  'Semester_1_lecture-4_Data_ManIpulation_Language.md': 'Semester 1/lecture-4 Data ManIpulation Language',
  'Semester_1_lecture-5_Data_Manipulation_Language.md': 'Semester 1/lecture-5 Data Manipulation Language',
  'Semester_1_lecture-6_Sql_Views_Access_Privileges.md': 'Semester 1/lecture-6 Sql Views Access Privileges',
  'Semester_1_lecture-7_Entity_Relationship_Modelling.md': 'Semester 1/lecture-7 Entity Relationship Modelling',
  'Semester_1_lecture-10_Normalisation.md': 'Semester 1/lecture-10 Normalisation',
  'Semester_2_lecture-5_Multilevel_Indexes_&_B+-Trees.md': 'Semester 2/lecture-5 Multilevel Indexes & B+-Trees',
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`

const parts = []
let total = 0
const summary = []

for (const [file, path] of Object.entries(PATHS)) {
  const augPath = new URL(file, AUG)
  const origPath = new URL(file, ORIG)
  if (!existsSync(augPath)) {
    console.error(`missing augmented note: ${file}`)
    process.exit(1)
  }
  const body = await readFile(augPath, 'utf8')
  const before = existsSync(origPath) ? (await readFile(origPath, 'utf8')).length : 0
  if (body.length === before) {
    console.error(`unchanged, refusing to write: ${file}`)
    process.exit(1)
  }
  total += body.length
  summary.push({ path, before, after: body.length })

  parts.push(`
-- ${path}
--   ${before} -> ${body.length} characters
update public.notes
   set content_md = ${q(body)}
 where module_id = ${q(MODULE)}
   and path      = ${q(path)};
`)
}

const sql = `-- Database Systems notes: the augmented Semester 1 and Semester 2 lectures.
--
-- Generated by scripts/build-database-notes-sql.mjs. Run the whole file in one
-- go; it is a single transaction and either every note updates or none does.
--
-- These are ${AUTHOR_NAME}'s notes. The augmentation adds figures, consoles and
-- practice questions around what she wrote; her prose is left as it was except
-- for two corrections noted in the commit history. The transaction runs as her
-- so the author recorded on every row stays hers.
--
-- Safe to re-run: every statement is an UPDATE matched on (module_id, path).

begin;

do $$
declare
  me uuid := '${AUTHOR}';
  found_username text;
begin
  select username into found_username from public.admin_users where id = me;
  if found_username is null then
    raise exception 'No admin_users row with id %, refusing to write', me;
  end if;
  if found_username <> ${q(AUTHOR_NAME)} then
    raise exception 'Expected % to be ${AUTHOR_NAME} but found %, refusing to write', me, found_username;
  end if;

  -- Three triggers on public.notes call auth.uid(); notes_track_author_trg
  -- writes it into note_authors.user_id, which is NOT NULL, so without this
  -- the whole transaction aborts.
  perform set_config('request.jwt.claims', json_build_object('sub', me)::text, true);
  perform set_config('request.jwt.claim.sub', me::text, true);
  -- Deliberately NOT set_config('role', 'authenticated'): that would switch the
  -- session role for the rest of the transaction and put these updates behind
  -- the notes RLS policies, which is not what the SQL editor is for. Setting
  -- the claims alone is enough for auth.uid() to return her id.
end $$;
${parts.join('')}
-- Every path above must have matched exactly one row. If any reports 0, the
-- note was renamed upstream and its augmentation has NOT been applied.
select path,
       length(content_md) as chars,
       (select username from public.admin_users u where u.id = na.user_id) as author
  from public.notes n
  left join lateral (
    select user_id from public.note_authors where note_id = n.id limit 1
  ) na on true
 where n.module_id = ${q(MODULE)}
   and n.path in (${Object.values(PATHS).map(q).join(',\n                  ')})
 order by n.path;

commit;
`

process.stdout.write(sql)

console.error(`${summary.length} note(s), ${total} characters total`)
for (const s of summary) {
  console.error(`  ${s.path.padEnd(52)} ${String(s.before).padStart(6)} -> ${String(s.after).padStart(6)}`)
}
